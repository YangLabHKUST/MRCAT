const {chromium} = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const ids = JSON.parse(fs.readFileSync('/tmp/mrcat-browser-roles.json', 'utf8'));
  const browser = await chromium.launch({headless: true, args: ['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
    const errors=[];page.on('pageerror', e=>errors.push(e.message));
    await page.goto((process.env.MRCAT_TEST_URL || 'http://127.0.0.1:18769/') + '#' + ids.completed);
    await page.waitForFunction(id=>state.snapshot?.state?.session_id===id,ids.completed);
    const conversation = await page.locator('#conversation-feed').innerText();
    assert.match(conversation,/Report Agent[\s\S]*Review passed/i);
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.task_history[0].task_id),'task1');
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.active_task),null);
    const report = await page.evaluate(()=>state.snapshot.final_report);
    assert.match(report.summary, /^workspace\/reports\/.+\/final_summary.md$/);
    const summaryResponse = await page.request.get(new URL(`api/sessions/${ids.completed}/artifacts/raw?summary=${encodeURIComponent(report.summary)}`, page.url()).href);
    assert.equal(summaryResponse.status(),200);
    assert.match(await summaryResponse.text(), /0\.2/);
    await page.screenshot({path:process.env.MRCAT_ROLES_SCREENSHOT || '/tmp/mrcat-roles-browser.png',fullPage:true});
    await page.evaluate(() => {
      const snapshot = structuredClone(state.snapshot);
      snapshot.mr.events.push({type: "evaluation_failed", content: "Fixture review failure: upstream HTTP 502", details: {agent: "mr"}});
      renderConversation(snapshot);
    });
    assert.match(await page.locator('#conversation-feed').innerText(), /Review unavailable[\s\S]*upstream HTTP 502/i);
    await page.evaluate(() => {
      const snapshot = structuredClone(state.snapshot);
      snapshot.mr.events.push({type: "evaluation_failed", content: "MR finalize model_call failed: upstream unavailable", details: {agent: "mr"}});
      renderConversation(snapshot);
    });
    assert.match(await page.locator('#conversation-feed').innerText(), /Summary unavailable[\s\S]*upstream unavailable/i);
    await page.evaluate(async id=>selectSession(id), ids.blocked);
    await page.waitForFunction(id=>state.snapshot?.state?.session_id===id,ids.blocked);
    assert.equal(await page.evaluate(()=>state.snapshot.state.status),'waiting_user');
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.task_history.length),0);
    assert.match(await page.locator('#conversation-feed').innerText(),/analysis is unfinished/);
    assert.equal(await page.locator('.mr-summary-download').count(),1);
    assert.doesNotMatch(await page.locator('#conversation-feed').innerText(),/END_FINAL_SUMMARY/);
    await page.evaluate(async id=>selectSession(id),ids.search);
    await page.waitForFunction(id=>state.snapshot?.state?.session_id===id,ids.search);
    await page.waitForSelector('.notebook-search-results .gwas-search-shortlist-table');
    assert.match(await page.locator('.notebook-search-results').innerText(),/fixture-cad/);
    assert.match(await page.locator('.notebook-search-results').innerText(),/Supplemental coronary atherosclerosis/);
    assert.match(await page.locator('.codeact-execution-details > .muted').textContent(),/Search Agent/);
    assert.equal(await page.locator('.codeact-cell').count(),1);
    assert.equal(await page.locator('details[data-current-plan="true"]').count(),0);
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.active_task),null);
    await page.reload();
    await page.waitForSelector('.notebook-search-results .gwas-search-shortlist-table');
    assert.match(await page.locator('.notebook-search-results').innerText(),/fixture-cad/);
    assert.match(await page.locator('.notebook-search-results').innerText(),/Supplemental coronary atherosclerosis/);
    await page.evaluate(async id=>selectSession(id),ids.proposal);
    await page.waitForFunction(id=>state.snapshot?.state?.session_id===id,ids.proposal);
    await page.waitForSelector('details[data-current-plan="true"]');
    assert.match(await page.locator('details[data-current-plan="true"] > summary').innerText(),/Proposed plan/);
    assert.match(await page.locator('details[data-current-plan="true"] .codeact-plan').innerText(),/gwas-qc[\s\S]*gwas-pair-prepare[\s\S]*mr-cml-ma/);
    assert.equal(await page.locator('.codeact-cell').count(),0);
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.active_task),null);
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.pending.kind),'plan_confirmation');
    assert.match(await page.locator('#conversation-feed').innerText(), /Confirm the plan shown above/);
    assert.equal(await page.evaluate(() => state.snapshot.mr.events.filter(e => e.type === 'plan_updated').length), 1);
    assert.equal(await page.evaluate(() => state.snapshot.mr.events.filter(e => e.type === 'question')[0].content),
      'Confirm the plan shown above, or describe the changes you want.');
    await page.reload();
    await page.waitForSelector('details[data-current-plan="true"]');
    assert.equal(await page.evaluate(()=>state.snapshot.mr.state.pending.kind),'plan_confirmation');
    assert.deepEqual(errors,[]);
    console.log('PASS: accepted report download, review failure visibility, blocked MR summary, Search results, proposed plan, task history and reload; no JS errors');
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exit(1);});
